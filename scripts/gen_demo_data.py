#!/usr/bin/env python3
"""Generate src/lib/payphone/demo-data.ts from the LIVE local engine.

The GitHub-Pages static demo has no backend, so it ships a snapshot of the
engine's own capability sheet (chains, assets, fees, rates). Regenerate any
time the catalog changes:  python3 scripts/gen_demo_data.py
"""
import json, urllib.request

ENGINE = "http://127.0.0.1:8080"

def get(path):
    return json.load(urllib.request.urlopen(ENGINE + path, timeout=15))["data"]

chains = get("/v1/chains")
assets = get("/v1/assets")
fees = get("/v1/fees/schedule")

# NOTE: the engine's /v1/rates normalizes symbols to uppercase, so mixed-case
# assets (cbBTC, cbETH) 400. Fetch in chunks, then fall back per-symbol with
# base-asset pricing for wrapped derivatives.
import urllib.error
syms = [a["symbol"] for a in assets["assets"]]
rates_list, seen = [], set()
for i in range(0, len(syms), 10):
    chunk = ",".join(syms[i:i+10])
    try:
        rates_list += get(f"/v1/rates?assets={chunk}")["rates"]
        seen.update(r["asset"] for r in rates_list)
    except urllib.error.HTTPError:
        for s in syms[i:i+10]:
            try:
                rates_list += get(f"/v1/rates?assets={s}")["rates"]
            except urllib.error.HTTPError:
                pass
        seen.update(r["asset"] for r in rates_list)

prices = {r["asset"]: r["usd"] for r in rates_list}
WRAPPED = {"WETH": "ETH", "WAVAX": "AVAX", "BTCB": "BTC", "WBTC": "BTC",
           "cbBTC": "BTC", "cbETH": "ETH", "WETH.E": "ETH"}
# Ballpark demo prices for assets the oracle upstreams couldn't price from the
# sandbox (CoinGecko rate-limits). Demo-only display values — the deployed
# engine always uses live aggregated prices.
FALLBACK_PRICES = {
    "XLM": 0.35, "HBAR": 0.22, "BCH": 480.0, "LTC": 105.0, "ATOM": 4.2,
    "FIL": 2.8, "INJ": 12.0, "STX": 0.9, "NEAR": 3.1, "APT": 4.5,
    "SUI": 2.4, "ICP": 5.2, "XMR": 210.0, "ETC": 19.0, "RENDER": 4.1,
}
for s in syms:
    if s not in prices:
        base = WRAPPED.get(s)
        if base and base in prices:
            prices[s] = prices[base]
        elif s in {"USDC", "USDT", "DAI", "TUSD", "FRAX", "PYUSD", "USDS"}:
            prices[s] = 1.0
        elif s in FALLBACK_PRICES:
            prices[s] = FALLBACK_PRICES[s]
        else:
            prices[s] = 0.0

networks = []
for n in chains["networks"]:
    networks.append({
        "name": n["name"], "kind": n["kind"], "chain_id": n["chain_id"],
        "native": n["native_asset"], "confirmations": n["confirmations_required"],
        "explorer_tx": n["explorer_tx"],
        "tokens": {t["symbol"]: {"address": t["address"], "decimals": t["decimals"]}
                   for t in n["settleable_tokens"]},
    })

out = f"""/**
 * DEMO DATA — snapshot of the live PayPhone engine capability sheet.
 *
 * GENERATED by scripts/gen_demo_data.py from the running Rust engine
 * ({ENGINE}). Do not edit by hand; regenerate instead.
 *
 * The GitHub-Pages static demo imports this so the browser-only engine
 * routes assets, tokens, decimals, confirmations and fees exactly like
 * production.
 */

export interface DemoNetwork {{
  name: string;
  kind: string;
  chain_id: number | null;
  native: string;
  confirmations: number;
  explorer_tx: string | null;
  tokens: Record<string, {{ address: string; decimals: number }}>;
}}

export interface DemoAsset {{
  symbol: string;
  name: string;
  decimals: number;
  default_chain: string;
  default_network: string;
  settleable: boolean;
  settleable_networks: {{ chain: string; network: string }}[];
}}

export const DEMO_NETWORKS: DemoNetwork[] = {json.dumps(networks, indent=2)};

export const DEMO_ASSETS: DemoAsset[] = {json.dumps(assets['assets'], indent=2)};

export const DEMO_PRICES: Record<string, number> = {json.dumps(prices, indent=2)};

export const DEMO_TIERS = {json.dumps(fees['schedule'], indent=2)};

export const DEMO_SPLIT = {json.dumps(fees['split'], indent=2)};
"""

target = "src/lib/payphone/demo-data.ts"
with open(target, "w") as f:
    f.write(out)
print(f"wrote {target}: {len(networks)} networks, {len(assets['assets'])} assets, "
      f"{len(prices)} prices, {len(fees['schedule'])} tiers")
